/** @param {string} tabId @param {string} [label] */
export function docTabLink(tabId, label = 'Open doc tab') {
  return {
    label,
    url: `https://docs.google.com/document/d/${DOC_ID}/edit?tab=${tabId}`,
  };
}

/** Fallback when the doc has no dedicated tab (orphaned section). */
